import { mkdir, stat, writeFile } from "node:fs/promises";
import { isAbsolute, join, relative, resolve, sep } from "node:path";
import { loadConfig } from "@uefn-devtools/core";

export const WORKFLOW_PATH = ".github/workflows/uefn-devtools.yml";

export const DEFAULT_RESULTS_DIR = ".devtools/results";

/** Builds the workflow; `resultsDir` is the project's results directory relative to the repository root. */
export function workflowTemplate(resultsDir: string = DEFAULT_RESULTS_DIR): string {
  return `# Generated by 'uefn init --github'.
name: UEFN DevTools

on:
  push:
    branches: [main]
  pull_request:

jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      # TypeScript tests import @uefn-devtools/test, so the project's own
      # dependencies must be installed, not just a global CLI. Add the CLI as a
      # devDependency (npm install --save-dev @uefn-devtools/cli; it is assumed
      # to be published to npm under this name). Use another install step if
      # you use pnpm or yarn.
      - name: Install dependencies
        run: |
          if [ -f package-lock.json ]; then npm ci; else npm install; fi
      # Uses the adapter from uefn-devtools.config.yaml. 'simulated' needs no UEFN.
      # The github reporter writes annotations and the job summary (the JUnit
      # results are summarized there; no third-party actions are involved).
      - name: Run tests
        run: npx uefn test --reporter github,junit
      - name: Upload results
        if: failure()
        uses: actions/upload-artifact@v4
        with:
          name: uefn-devtools-results
          path: ${resultsDir}
          include-hidden-files: true
          if-no-files-found: ignore

  # UNVERIFIED: running against real UEFN (adapter: mcp) needs a self-hosted
  # Windows runner with UEFN and Fortnite installed and signed in, plus a
  # configured 'mcp' section. Headless UEFN is not known to work (see
  # docs/capabilities.md). Uncomment and adapt only after verifying it locally.
  #
  # test-uefn:
  #   runs-on: [self-hosted, windows, uefn]
  #   steps:
  #     - uses: actions/checkout@v4
  #     - uses: actions/setup-node@v4
  #       with:
  #         node-version: 22
  #     - run: npm ci
  #     - run: npx uefn test --adapter mcp --reporter github,junit
  #     - name: Upload results
  #       if: failure()
  #       uses: actions/upload-artifact@v4
  #       with:
  #         name: uefn-devtools-results-uefn
  #         path: ${resultsDir}
  #         include-hidden-files: true
  #         if-no-files-found: ignore
`;
}

export const WORKFLOW_TEMPLATE = workflowTemplate();

/** The configured paths.results relative to `root`, in the forward-slash form workflows use; the default when unusable. */
async function resultsDirFor(root: string): Promise<string> {
  try {
    const loaded = await loadConfig(root);
    const rel = relative(root, resolve(loaded.root, loaded.config.paths.results));
    if (rel === "" || rel.startsWith("..") || isAbsolute(rel)) return DEFAULT_RESULTS_DIR;
    return rel.split(sep).join("/");
  } catch {
    return DEFAULT_RESULTS_DIR;
  }
}

/** Writes the workflow into `root`; refuses to overwrite an existing file. */
export async function initGithubWorkflow(root: string): Promise<number> {
  const path = join(root, WORKFLOW_PATH);
  if (await stat(path).then(() => true, () => false)) {
    console.error(`${WORKFLOW_PATH} already exists`);
    return 2;
  }
  await mkdir(join(root, ".github", "workflows"), { recursive: true });
  await writeFile(path, workflowTemplate(await resultsDirFor(root)), { flag: "wx" });
  console.log(`Wrote ${WORKFLOW_PATH}`);
  return 0;
}
