import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { parseDuration } from "@uefn-devtools/protocol";
import { findYamlTest, generateScenario, scenarioLocations } from "@uefn-devtools/test";
import { openEngine, print, str, UsageError, type Command } from "../shared.ts";

/** The test id named in a generated scenario file's header, if the file is one. */
export function generatedScenarioOwner(verse: string): string | undefined {
  return /^# Generated by `uefn scenario (.*?)` from /.exec(verse)?.[1];
}

/**
 * Ids such as `foo-bar` and `foo_bar` share a class and file name, so an
 * existing file is only replaced when it was generated for the same test.
 */
export function overwriteConflict(existing: string | undefined, id: string, file: string): string | undefined {
  if (existing === undefined) return undefined;
  const owner = generatedScenarioOwner(existing);
  if (owner === id) return undefined;
  return owner === undefined
    ? `${file} exists and was not generated by 'uefn scenario'; move it or pass --out`
    : `${file} was generated for test '${owner}', whose class name collides with '${id}'; give one of the tests a distinct id or pass --out`;
}

export const scenario: Command = {
  name: "scenario",
  usage: "scenario <test-id>",
  summary: "Generate the in-game Verse device that performs a YAML test's player actions",
  options: { out: { type: "string" } },
  optionHelp: ["--out <dir>            Where to write the .verse file (default scenario.output)"],
  async run(values, positionals) {
    const id = positionals[0];
    if (!id) throw new UsageError("usage: uefn scenario <test-id>");
    const engine = await openEngine(values);
    try {
      const config = engine.config;
      // Only YAML tests are read, and only as data: nothing in the project is executed.
      const found = await findYamlTest(resolve(engine.root, config.paths.tests), id);
      if (!found) throw new UsageError(`no YAML test with id '${id}' (scenarios are generated from YAML tests)`);

      const generated = generateScenario(found.test, { id, locations: scenarioLocations(config), startDelayMs: parseDuration(config.scenario.start_delay) });
      const dir = resolve(engine.root, str(values, "out") ?? config.scenario.output);
      await mkdir(dir, { recursive: true });
      const path = join(dir, generated.fileName);
      const existing = await readFile(path, "utf8").catch(() => undefined);
      const conflict = overwriteConflict(existing, id, relative(engine.root, path));
      if (conflict) throw new UsageError(conflict);
      await writeFile(path, generated.verse);
      const data = {
        test: id,
        file: relative(engine.root, path),
        className: generated.className,
        fingerprint: generated.fingerprint,
        plan: generated.plan,
        warnings: generated.warnings,
      };
      print(values, data, () => {
        console.log(`Wrote ${data.file} (${generated.plan.length} step(s) from ${relative(engine.root, found.file)})`);
        for (const s of generated.plan) console.log(`  ${s.index}. ${s.description}`);
        for (const w of generated.warnings) console.log(`warning: ${w}`);
        console.log(`\nNext: compile, place one ${generated.className} device (and no other scenario device) in the level, and set scenario.enabled: true.`);
        if (!config.scenario.enabled) console.log("scenario.enabled is false, so player actions are not routed to the device yet.");
      });
      return 0;
    } finally {
      await engine.close();
    }
  },
};
