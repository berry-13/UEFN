import assert from "node:assert/strict";
import { test } from "node:test";
import { generateScenario, YamlTestSchema } from "@uefn-devtools/test";
import { generatedScenarioOwner, overwriteConflict } from "../src/commands/scenario.ts";

test("a generated scenario is only overwritten for the same test id", () => {
  const doc = YamlTestSchema.parse({ name: "x", setup: ["start_game"], steps: [{ damage: { player: 1, amount: 1 } }] });
  const first = generateScenario(doc, { id: "foo-bar", locations: {}, startDelayMs: 0 });
  const second = generateScenario(doc, { id: "foo_bar", locations: {}, startDelayMs: 0 });
  assert.equal(first.fileName, second.fileName, "the ids collide");
  assert.equal(generatedScenarioOwner(first.verse), "foo-bar");
  assert.equal(overwriteConflict(undefined, "foo_bar", "f.verse"), undefined);
  assert.equal(overwriteConflict(first.verse, "foo-bar", "f.verse"), undefined);
  assert.match(overwriteConflict(first.verse, "foo_bar", "f.verse")!, /generated for test 'foo-bar', whose class name collides with 'foo_bar'/);
  assert.match(overwriteConflict("hand written", "foo_bar", "f.verse")!, /not generated by 'uefn scenario'/);
});
