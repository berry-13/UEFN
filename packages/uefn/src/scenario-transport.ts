import type { CommandResult, RuntimeCommand, RuntimeEvent } from "@uefn-devtools/protocol";
import type { RuntimeTransport } from "./adapter.ts";
import type { Clock } from "./clock.ts";

/** `arg` of a spawn step the device adds before moving a downed player (IMPLICIT_SPAWN in @uefn-devtools/test). */
const IMPLICIT_SPAWN = "implicit";

/** Player actions a generated scenario device performs inside the match. */
export const SCENARIO_ACTIONS = ["spawn_player", "teleport", "leave_area", "damage_player", "eliminate_player"] as const;
type ScenarioAction = (typeof SCENARIO_ACTIONS)[number];

export interface ScenarioTransportOptions {
  clock: Clock;
  /** Session-clock ms to wait for each step's confirmation. */
  stepTimeoutMs: number;
}

interface Report {
  index: number;
  action: string;
  player?: string;
  /** The step's command argument, from devices generated with argument reports. */
  arg?: string;
  failed?: string;
}

/** The command argument a scenario step was generated from (see ScenarioPlanStep.arg). */
function commandArg(command: RuntimeCommand): string | undefined {
  switch (command.type) {
    case "teleport":
      return command.location;
    case "leave_area":
      return command.area;
    case "damage_player":
      return String(command.amount);
    case "eliminate_player":
      return command.by ?? "";
    default:
      return undefined;
  }
}

/**
 * Wraps the session transport so player actions resolve when the in-game
 * scenario device (generated by `uefn scenario`) reports the matching step.
 * The device runs its steps on its own; the host only checks that each one
 * happened, in order, and fails loudly on a mismatch, a device-side failure
 * or a timeout. A new `scenario.started` (match restart) resets the cursor.
 *
 * Scenario events carry the test id (`scenario`) and the plan fingerprint
 * (`plan`). The transport locks onto the first scenario that starts in a
 * match and ignores reports from any other; a second scenario, or a second
 * build of the same one, starting in the same match fails the next step
 * with an explanation, since only one device may be placed per test.
 * `game.ended` releases the lock.
 */
export class ScenarioTransport implements RuntimeTransport {
  readonly name: string;
  private reports: Report[] = [];
  private cursor = 0;
  /** The scenario (id and plan fingerprint) this match is locked onto. */
  private locked: { id: string; plan?: string } | undefined;
  private conflict: string | undefined;
  /** The scenario the running test was generated into, when the host knows it. */
  private expected: { id: string; plan: string } | undefined;
  /** Why pending steps were abandoned (the match ended under them). */
  private abandoned: string | undefined;
  private waiters = new Set<() => void>();

  constructor(
    private readonly inner: RuntimeTransport,
    private readonly options: ScenarioTransportOptions,
  ) {
    this.name = `${inner.name}+scenario`;
  }

  start(): Promise<void> {
    return this.inner.start();
  }

  stop(): Promise<void> {
    return this.inner.stop();
  }

  async *receive(): AsyncIterable<RuntimeEvent> {
    for await (const event of this.inner.receive()) {
      this.observe(event);
      yield event;
    }
  }

  /** Exposed for tests: feeds one event through the step tracker. */
  observe(event: RuntimeEvent): void {
    const p = event.payload;
    if (event.type === "game.ended") {
      // Reports belong to the match that produced them: a retry in the next
      // match must not consume them, and a step still waiting fails now.
      this.locked = undefined;
      this.conflict = undefined;
      this.reports = [];
      this.cursor = 0;
      this.abandoned = "the match ended before the step was reported";
      for (const wake of this.waiters) wake();
      this.abandoned = undefined;
      return;
    }
    if (!event.type.startsWith("scenario.")) return;
    const id = typeof p["scenario"] === "string" ? p["scenario"] : "";
    if (event.type === "scenario.started") {
      const plan = typeof p["plan"] === "string" ? p["plan"] : undefined;
      const mismatch = this.locked ? undefined : this.mismatch(id, plan);
      if (mismatch) {
        this.conflict = mismatch;
        this.locked = { id, ...(plan !== undefined ? { plan } : {}) };
      } else if (this.locked && this.locked.id !== id) {
        this.conflict = `scenario devices for '${this.locked.id || "(untagged)"}' and '${id || "(untagged)"}' both run in this match; place one scenario device per test`;
      } else if (this.locked && this.locked.plan !== plan) {
        this.conflict = `two builds of scenario '${id}' (plans ${this.locked.plan ?? "?"} and ${plan ?? "?"}) run in this match; remove the stale device and regenerate it with 'uefn scenario'`;
      } else {
        // First start in this match, or a restart of the same device.
        this.locked = { id, ...(plan !== undefined ? { plan } : {}) };
        this.reports = [];
        this.cursor = 0;
      }
    } else if (this.locked && this.locked.id !== id) {
      return;
    } else if (event.type === "scenario.step" && typeof p["index"] === "number") {
      this.reports.push({
        index: p["index"],
        action: String(p["action"] ?? ""),
        ...(typeof p["player"] === "string" ? { player: p["player"] } : {}),
        ...(typeof p["arg"] === "string" ? { arg: p["arg"] } : {}),
      });
    } else if (event.type === "scenario.failed" && typeof p["index"] === "number") {
      this.reports.push({ index: p["index"], action: "", failed: String(p["reason"] ?? "step failed") });
    } else {
      return;
    }
    for (const wake of this.waiters) wake();
  }

  /**
   * The scenario (test id and plan fingerprint) the running test generates,
   * so a single stale or foreign device is refused, not only a second one.
   * `undefined` when the host cannot tell (a TypeScript test).
   */
  expectScenario(expected: { id: string; plan: string } | undefined): void {
    this.expected = expected;
    // A device may have started (and been locked onto) before the test said
    // which one it expects: check it now.
    if (expected && this.locked && !this.conflict) {
      const conflict = this.mismatch(this.locked.id, this.locked.plan);
      if (conflict) {
        this.conflict = conflict;
        for (const wake of this.waiters) wake();
      }
    }
  }

  /** Why a device that started as `id` / `plan` is not the expected one, if it is not. */
  private mismatch(id: string, plan: string | undefined): string | undefined {
    const expected = this.expected;
    if (!expected) return undefined;
    if (expected.id !== id) {
      return `the scenario device in this match is for '${id || "(untagged)"}', not '${expected.id}'; place the device generated for this test ('uefn scenario ${expected.id}')`;
    }
    if (expected.plan !== plan) {
      return `the placed scenario device for '${id}' is stale (plan ${plan ?? "?"}, the test generates ${expected.plan}); regenerate it with 'uefn scenario ${id}' and compile`;
    }
    return undefined;
  }

  async command(command: RuntimeCommand): Promise<CommandResult> {
    if (!(SCENARIO_ACTIONS as readonly string[]).includes(command.type)) return this.inner.command(command);
    let expected = this.cursor;
    if (this.conflict) return { ok: false, error: this.conflict };
    let report = await this.next(expected);
    const player = "player" in command ? command.player : undefined;
    const isReport = (r: typeof report): r is Report => typeof r === "object" && !r.failed;
    // A spawn the device adds before moving a downed player. The host sends it
    // only while its observed state still shows the player down; once the
    // device's own spawn report has arrived it moves the player directly.
    if (isReport(report) && report.action === "spawn_player" && report.arg === IMPLICIT_SPAWN && command.type !== "spawn_player" && report.player === player) {
      this.cursor += 1;
      expected = this.cursor;
      report = await this.next(expected);
    }
    // The reverse: the host saw the player go down (a lethal damage step) and
    // spawns them before moving them, but the device planned no spawn there.
    // It moves the current, respawned character, so the move covers the spawn.
    if (command.type === "spawn_player" && isReport(report) && report.action === "teleport" && report.player === player) {
      return { ok: true };
    }
    if (this.conflict) return { ok: false, error: this.conflict };
    if (typeof report === "string") return { ok: false, error: `scenario step ${expected} (${command.type}) was not reported: ${report}` };
    if (!report) {
      return {
        ok: false,
        error: `scenario step ${expected} (${command.type}) was not reported within ${this.options.stepTimeoutMs}ms; is the generated scenario device placed in the level and the scenario up to date ('uefn scenario')?`,
      };
    }
    this.cursor += 1;
    if (report.failed) return { ok: false, error: `scenario step ${expected} failed in game: ${report.failed}` };
    if (report.action !== (command.type as ScenarioAction)) {
      return { ok: false, error: `scenario step ${expected} was '${report.action}' in game but the test sent '${command.type}'; regenerate the scenario with 'uefn scenario'` };
    }
    if (player !== undefined && report.player !== undefined && report.player !== player) {
      return { ok: false, error: `scenario step ${expected} acted on '${report.player}' but the test expected '${player}'` };
    }
    const arg = commandArg(command);
    if (arg !== undefined && report.arg !== undefined && report.arg !== arg) {
      return {
        ok: false,
        error: `scenario step ${expected} (${command.type}) ran with '${report.arg}' in game but the test sent '${arg}'; the placed device is stale, regenerate it with 'uefn scenario'`,
      };
    }
    return { ok: true };
  }

  supportedCommands(): readonly RuntimeCommand["type"][] {
    return [...new Set([...this.inner.supportedCommands(), ...SCENARIO_ACTIONS])];
  }

  resetObservedState(): void {
    this.inner.resetObservedState?.();
  }

  /** The report for step `index`; a string when the step was abandoned; undefined on timeout. */
  private next(index: number): Promise<Report | string | undefined> {
    const find = () => this.reports.find((r) => r.index === index);
    const found = find();
    if (found) return Promise.resolve(found);
    return new Promise((resolve) => {
      let done = false;
      const finish = (value: Report | string | undefined) => {
        if (done) return;
        done = true;
        this.waiters.delete(check);
        clearTimeout(timer);
        resolve(value);
      };
      const check = () => {
        const r = find();
        if (r) finish(r);
        else if (this.abandoned) finish(this.abandoned);
        // A second scenario device fails the step now, not at the timeout.
        else if (this.conflict) finish(undefined);
      };
      this.waiters.add(check);
      const timer = setTimeout(() => finish(undefined), Math.max(0, this.options.clock.toWallMs(this.options.stepTimeoutMs)));
    });
  }
}
